"""Controlled displacement test using native monitors and native recovery graph.

The recovery graph is explicitly authored here, not generated by an LLM.
Only the official misplaced_object function changes an object pose, once.
"""
from __future__ import annotations

import copy
from functools import partial
import json
import math
from pathlib import Path
from types import SimpleNamespace

from agentchord_console.carry_demo import select_bundle
from agentchord_console.grasp_check import value_json
from agentchord_console.plan_check import ShadowEnv, clone, IKFailure, serializable
from agentchord_console.task_plan import _hash, _pose_xyz

EDGE = "e07_return"
EDGE_STEP = 20
OBJECT = "fork"
SHIFT = [0., .06, 0.]
THRESHOLD = .02
STEP_LIMIT = 1100
INJECTION_PROTOCOL = "native_setter_then_physics_v3"
SETTLED_Y_RANGE = (.04, .08)
AXIS_TOLERANCE = .003
MIN_TARGET_ERROR = .03


def assess_injection(event):
    """Check the setter request separately from the post-physics displacement.

    This is the v3 controlled-test protocol, not a revision of old results.
    The actual displacement must exceed twice the native monitor threshold,
    remain near the commanded magnitude, and produce a clearly unmet goal.
    """
    report = {"protocol": INJECTION_PROTOCOL, "valid": False,
        "settled_y_range_m": list(SETTLED_Y_RANGE), "cross_axis_tolerance_m": AXIS_TOLERANCE,
        "min_target_error_m": MIN_TARGET_ERROR, "submitted_delta_tolerance_m": 1e-6}
    def xyz(value):
        if (not isinstance(value, list) or len(value) != 3 or any(
            not isinstance(x, (int, float)) or isinstance(x, bool) or not math.isfinite(x) for x in value)):
            raise ValueError("Expected a finite XYZ vector.")
        return value
    try:
        before = {name: xyz(event["before_objects"][name]) for name in ("plate", "fork", "spoon")}
        after = {name: xyz(event["after_objects"][name]) for name in before}
        delta = [after[OBJECT][i]-before[OBJECT][i] for i in range(3)]
        submitted = xyz(event["submitted_pose_xyz_m"])
        submitted_delta = [submitted[i]-before[OBJECT][i] for i in range(3)]
        checks = {
            "correct_protocol": event.get("protocol") == INJECTION_PROTOCOL,
            "correct_event": event.get("edge") == EDGE and event.get("edge_step") == EDGE_STEP and event.get("object") == OBJECT,
            "correct_request": math.dist(xyz(event["requested_xyz_m"]), SHIFT) <= 1e-9,
            "single_native_setter": event.get("native_setter_calls") == 1 and event.get("native_setter_completed") is True,
            "submitted_delta_matches_request": math.dist(submitted_delta, SHIFT) <= 1e-6,
            "native_physics_updates": event.get("observed_physics_updates") == [100],
            "recorded_delta_matches_poses": math.dist(delta, xyz(event["measured_xyz_m"])) <= 1e-6,
            "before_goal_met": all(abs(before[name][1]-before["plate"][1]-target) <= .02 for name,target in (("fork",.16),("spoon",-.16))),
            "settled_y_in_range": SETTLED_Y_RANGE[0] <= delta[1] <= SETTLED_Y_RANGE[1],
            "small_cross_axis_motion": math.hypot(delta[0], delta[2]) <= AXIS_TOLERANCE,
            "clear_goal_displacement": abs(after[OBJECT][1]-after["plate"][1]-.16) >= MIN_TARGET_ERROR,
            "other_objects_preserved": all(math.dist(before[name], after[name]) <= AXIS_TOLERANCE for name in ("plate","spoon")),
        }
        report.update(checks=checks, valid=all(checks.values()), submitted_delta_m=submitted_delta,
            measured_delta_m=delta, post_physics_drift_from_submitted_m=[delta[i]-submitted_delta[i] for i in range(3)])
    except (KeyError, TypeError, ValueError) as exc:
        report["error"] = f"{type(exc).__name__}: {exc}"
    return report


class _InjectionAudit:
    """Observe arguments while forwarding native setter/update calls once."""
    def __init__(self, env):
        self.original_sim = env.sim
        self.setter_calls, self.setter_completed = 0, False
        self.submitted_xyz, self.updates = None, []
        audit = self
        class Rigid:
            def __init__(self, original): self.original = original
            def get_local_pose(self, *args, **kwargs): return self.original.get_local_pose(*args, **kwargs)
            def set_local_pose(self, pose):
                value = serializable(pose)
                matrix = value[0] if len(value) == 1 else value
                audit.setter_calls += 1
                audit.submitted_xyz = [matrix[i][3] for i in range(3)]
                result = self.original.set_local_pose(pose)
                audit.setter_completed = True
                return result
        class Sim:
            def get_rigid_object(self, name):
                original = audit.original_sim.get_rigid_object(name)
                return Rigid(original) if name == OBJECT else original
            def update(self, *args, **kwargs):
                audit.updates.append(kwargs.get("step", args[0] if args else None))
                return audit.original_sim.update(*args, **kwargs)
        self.env = SimpleNamespace(sim=Sim())

    def details(self):
        return {"protocol": INJECTION_PROTOCOL, "native_setter_calls": self.setter_calls,
            "native_setter_completed": self.setter_completed, "submitted_pose_xyz_m": self.submitted_xyz,
            "observed_physics_updates": self.updates}


def with_reset_targets(nominal, env):
    """Record real reset poses without adding another pre-return tool offset."""
    bundle = copy.deepcopy(nominal)
    targets = {}
    for side in ("left", "right"):
        pose = serializable(getattr(env, f"{side}_arm_init_xpos"))
        if (not isinstance(pose, list) or len(pose) != 4
                or any(not isinstance(row, list) or len(row) != 4 for row in pose)
                or any(not isinstance(v, (int, float)) or isinstance(v, bool)
                       or not math.isfinite(v) for row in pose for v in row)):
            raise ValueError("Expected finite measured 4x4 initial arm poses.")
        targets[f"{side}_arm"] = pose
    bundle["metadata"].update(recovery_reset_targets=targets,
                             recovery_reset_strategy="native_move_to_recorded_initial_pose_v2")
    return bundle


def native_action_kwargs(env, action):
    """Convert a JSON reset matrix to the SDK's existing pose tensor type."""
    kwargs = clone(action["kwargs"])
    if action["fn"] == "move_to_target_pose":
        reference = getattr(env, f"{kwargs['robot_name']}_current_xpos")
        kwargs["target_pose"] = _as_like(reference, kwargs["target_pose"])
    return kwargs


def recovery_edges(nominal, distance=.1):
    task = nominal["task_graph"]
    path = task["edges"]
    actions = [path[-1], *path]
    nodes = [{"id": f"r{i}_state", "semantic": "Planned controlled recovery state"} for i in range(1, 8)]
    edges = []
    for i, source in enumerate(actions, 1):
        stage = "reset" if i == 1 else source["id"].split("_", 1)[1]
        edge = {"id": f"r{i:02d}_{stage}",
                "source": path[-1]["source"] if i == 1 else nodes[i-2]["id"],
                "target": task["goal"] if i == 8 else nodes[i-1]["id"],
                "left_arm_action": copy.deepcopy(source["left_arm_action"]),
                "right_arm_action": copy.deepcopy(source["right_arm_action"])}
        if stage == "reset":
            targets = nominal["metadata"]["recovery_reset_targets"]
            for arm in ("left_arm", "right_arm"):
                edge[f"{arm}_action"] = {"fn": "move_to_target_pose", "kwargs": {
                    "robot_name": arm, "target_pose": copy.deepcopy(targets[arm]), "sample_num": 50}}
        if stage == "grasp":
            for arm in ("left_arm", "right_arm"):
                edge[f"{arm}_action"]["kwargs"]["pre_grasp_dis"] = distance
        edges.append(edge)
    return nodes, edges


def with_recovery(nominal, enabled, distance=.1):
    bundle = copy.deepcopy(nominal)
    nodes, edges = recovery_edges(nominal, distance)
    if enabled:
        bundle["recovery_graph"] = {
            "task": bundle["task_graph"]["task"], "recovery_nodes": nodes, "recovery_edges": edges,
            "recovery_branches": [{"edge_id": EDGE, "failure_name": "fork_displaced_during_return",
                "monitor_sequence": [{"fn": "monitor_object_moved", "kwargs": {"obj_name": OBJECT, "threshold": THRESHOLD}}],
                "recovery_edges": [edge["id"] for edge in edges]}]}
    bundle["metadata"].update(recovery_enabled=bool(enabled),
        console_scope="controlled native displacement/monitor/recovery diagnostic; no LLM generation",
        recovery_author="local reviewed explicit graph",
        nominal_graph_hash=_hash(bundle["task_graph"]),
        disturbance={"edge": EDGE, "edge_step": EDGE_STEP, "object": OBJECT, "relative_xyz_m": SHIFT,
                     "method": "native misplaced_object", "native_settle_physics_steps": 100,
                     "protocol": INJECTION_PROTOCOL, "settled_y_range_m": list(SETTLED_Y_RANGE),
                     "cross_axis_tolerance_m": AXIS_TOLERANCE, "min_target_error_m": MIN_TARGET_ERROR})
    return bundle


class _PoseReadOnly:
    def __init__(self, pose): self.pose = clone(pose)
    def get_local_pose(self, to_matrix=True):
        if not to_matrix: raise ValueError("Only matrix pose reads are supported.")
        return clone(self.pose)


class _HypotheticalSim:
    def __init__(self, original, poses): self.original, self.poses = original, poses
    def get_rigid_object_uid_list(self): return clone(self.original.get_rigid_object_uid_list())
    def get_rigid_object(self, name):
        return _PoseReadOnly(self.poses[name]) if name in self.poses else self.original.get_rigid_object(name)


def _as_like(reference, values):
    return reference.new_tensor(values) if hasattr(reference, "new_tensor") else clone(values)


def assess_predicted_robot_return(state, original):
    """Check cloned SDK caches against original joint targets, never write poses.

    A pose-only reset can select different IK joints. An idle arm also retains
    the interrupted return's measured joints; neither proves joint completion.
    """
    def vector(value, size):
        values = value_json(value)
        if isinstance(values, list) and len(values) == 1 and isinstance(values[0], list):
            values = values[0]
        if not isinstance(values,list) or len(values) != size or any(
            isinstance(v,bool) or not isinstance(v,(int,float)) or not math.isfinite(v) for v in values):
            raise ValueError("Invalid predicted robot joint/gripper state.")
        return values
    arms = {}
    open_state = vector(original.open_state,1)
    for side in ("left","right"):
        current = vector(getattr(state,f"{side}_arm_current_qpos"),6)
        target = vector(getattr(original,f"{side}_arm_init_qpos"),6)
        gripper = vector(getattr(state,f"{side}_arm_current_gripper_state"),1)
        error = max(abs(a-b) for a,b in zip(current,target))
        grip_error = abs(gripper[0]-open_state[0])
        arms[side] = {"predicted_qpos":current,"initial_qpos_target":target,
            "predicted_gripper_state":gripper,"open_gripper_target":open_state,
            "max_joint_error_rad":error,"gripper_error_m":grip_error,
            "passed":error <= .01 and grip_error <= .002}
    return {"passed":all(arm["passed"] for arm in arms.values()),"arms":arms,
        "joint_tolerance_rad":.01,"gripper_tolerance_m":.002,
        "scope":"Cloned SDK terminal joint/gripper cache prediction; measured post-execution return remains independently required."}


def preflight_recovery(env, nominal, actions_module=None, *, recovery_plan=None, require_return=False):
    """Predict the interrupted return and recovery with cloned SDK state only.

    Future poses assume successful nominal placement with the initial rotation.
    This predicts kinematic feasibility, not contacts or the eventual live pose.
    """
    if actions_module is None:
        from embodichain.agents.agentchord import atom_actions as actions_module
    report = {"status": "error", "attempts": [], "terminal_return_required":bool(require_return),
        "scope": "read_only_predicted_interrupted_return_and_recovery",
        "assumptions": "Nominal placement succeeds; cutlery rests at initial Z with initial rotation. Actual dynamics and grasp retention are not predicted."}
    shadow = None
    try:
        nominal = with_reset_targets(nominal, env)
        predicted = ShadowEnv(env)
        # Generate native trajectories on copied state, never drive or step.
        for edge in nominal["task_graph"]["edges"]:
            return_rows = {}
            for side in ("left", "right"):
                action = edge[f"{side}_arm_action"]
                predicted.active_edge, predicted.active_arm = edge["id"], f"{side}_arm"
                predicted.active_action = action["fn"]
                trajectory = getattr(actions_module, action["fn"])(env=predicted, **clone(action["kwargs"]))
                if edge["id"] == EDGE:
                    rows = value_json(trajectory)
                    if len(rows) < EDGE_STEP or len(rows[EDGE_STEP-1]) != 8:
                        raise ValueError("Expected the pinned 6-joint + 2-gripper native trajectory layout.")
                    return_rows[side] = rows[EDGE_STEP-1]
            if edge["id"] == EDGE:
                for side, row in return_rows.items():
                    qpos = _as_like(getattr(predicted, f"{side}_arm_current_qpos"), row[:-2])
                    predicted.set_current_qpos_agent(qpos, is_left=side == "left")
                    predicted.set_current_xpos_agent(predicted.get_arm_fk(qpos=qpos, is_left=side == "left"), is_left=side == "left")
                    predicted.set_current_gripper_state_agent(_as_like(getattr(predicted, f"{side}_arm_current_gripper_state"), [row[-1]]), is_left=side == "left")
        poses = {}
        plate = _pose_xyz(env, "plate")
        for obj, y in (("fork", .16 + SHIFT[1]), ("spoon", -.16)):
            pose = clone(env.sim.get_rigid_object(obj).get_local_pose(to_matrix=True))
            if hasattr(pose, "squeeze"):
                matrix = pose.squeeze(0)
                matrix[0, 3], matrix[1, 3] = plate[0], plate[1] + y
            else:
                matrix = pose[0] if len(pose) == 1 else pose
                matrix[0][3], matrix[1][3] = plate[0], plate[1] + y
            poses[obj] = pose
            predicted.obj_info[obj]["pose"] = clone(matrix)
        predicted.sim = _HypotheticalSim(predicted.sim, poses)
        report["hypothetical_object_poses"] = {k: serializable(v) for k, v in poses.items()}
        for distance in ((None,) if recovery_plan is not None else (.1, .05, .03)):
            shadow = ShadowEnv(predicted)
            attempt = {"pre_grasp_dis_m": distance, "edges": [],
                       "plan_source": "model_selected_fixed_plan" if recovery_plan is not None else "local_candidates"}
            report["attempts"].append(attempt)
            try:
                edges = clone(recovery_plan) if recovery_plan is not None else recovery_edges(nominal, distance)[1]
                for edge in edges:
                    stage = {"id": edge["id"], "arms": []}
                    attempt["edges"].append(stage)
                    for side in ("left", "right"):
                        action = edge.get(f"{side}_arm_action")
                        if action is None:
                            continue  # Native drive holds the other arm at its cached state.
                        shadow.active_edge, shadow.active_arm, shadow.active_action = edge["id"], f"{side}_arm", action["fn"]
                        trajectory = getattr(actions_module, action["fn"])(env=shadow, **native_action_kwargs(shadow, action))
                        stage["arms"].append({"arm": f"{side}_arm", "trajectory_steps": len(trajectory)})
                if require_return:
                    attempt["predicted_robot_return"] = assess_predicted_robot_return(shadow,env)
                    if not attempt["predicted_robot_return"]["passed"]:
                        attempt.update(status="failed",failed_edge="terminal_dual_arm_goal",
                            reason="Recovery path leaves an arm/gripper outside its final return target.")
                        report["status"] = "failed"
                        return report
                attempt["status"] = "passed"
                report.update(status="passed", selected_grasp_distance_m=distance)
                return report
            except IKFailure as exc:
                attempt.update(status="failed", reason=str(exc), failed_edge=shadow.active_edge)
                # Changing a later approach distance cannot repair reset failure.
                if shadow.active_edge == "r01_reset":
                    report["status"] = "failed"
                    return report
            finally:
                attempt["ik_calls"] = copy.deepcopy(shadow.ik_calls)
        report["status"] = "failed"
    except IKFailure as exc:
        report.update(status="failed", reason=str(exc))
    except Exception as exc:
        report.update(status="error", error=f"{type(exc).__name__}: {exc}")
    return report


def prepare_bundle(env, enabled, *, progress=None):
    nominal, nominal_check = select_bundle(env, progress=progress)
    report = {"status": nominal_check["status"], "nominal": nominal_check}
    if nominal is None: return None, report
    nominal = with_reset_targets(nominal, env)
    recovery_check = preflight_recovery(env, nominal)
    report["recovery_prediction"] = recovery_check
    report["status"] = recovery_check["status"]
    if report["status"] != "passed": return None, report
    return with_recovery(nominal, enabled, recovery_check["selected_grasp_distance_m"]), report


class RecoveryObserver:
    """Log real graph transitions and inject once after a native physics step."""
    def __init__(self, env, run_dir, enabled, write_json, snapshot):
        self.env, self.run_dir, self.enabled = env, Path(run_dir), bool(enabled)
        self.write_json, self.snapshot = write_json, snapshot
        self.trace = None
        self.edge, self.edge_step = None, 0
        self.injected = False
        self.detected = False
        self.events, self.checks = [], []
        self.original_compile = self.original_drive = None

    def emit(self, kind, **details):
        event = {"event": kind, "step": self.trace.step_index if self.trace else 0,
                 "edge": self.edge, "edge_step": self.edge_step, **details}
        self.events.append(event)
        self.write_json(self.run_dir / "recovery_events.json", {"enabled": self.enabled, "events": self.events})
        if kind in {"injection", "detection", "recovery_edge_start", "graph_edge_end"}:
            print(f"[恢复验证] {kind}：{json.dumps(event, ensure_ascii=False)}", flush=True)

    def begin(self, edge):
        if self.edge == edge.id: return
        self.edge, self.edge_step = edge.id, 0
        if self.trace: self.trace.phase = edge.id
        self.emit("recovery_edge_start" if edge.is_recovery else "nominal_edge_start")

    def check(self, native_monitor, *, original=None):
        verdict = bool(original() if original is not None else native_monitor(
            env=self.env, obj_name=OBJECT, threshold=THRESHOLD))
        entry = {"step": self.trace.step_index, "edge": self.edge, "edge_step": self.edge_step,
                 "fn": "monitor_object_moved", "threshold_m": THRESHOLD, "result": verdict,
                 "role": "native_graph_monitor" if self.enabled else "read_only_off_group_observer"}
        self.checks.append(entry)
        self.write_json(self.run_dir / "monitor_checks.json", self.checks)
        if verdict and not self.detected:
            self.detected = True
            self.emit("detection", **{k: v for k, v in entry.items() if k not in {"step", "edge", "edge_step"}})
        return verdict

    def after_step(self, trace):
        if trace.step_index > STEP_LIMIT:
            raise RuntimeError("Controlled recovery exceeded its physics-step budget.")
        if self.edge is None: return
        self.edge_step += 1
        if self.edge == EDGE and self.edge_step == EDGE_STEP and not self.injected:
            before = {name: _pose_xyz(self.env, name) for name in ("plate", "fork", "spoon")}
            if not all(abs(before[name][1]-before["plate"][1]-target) <= .02
                       for name, target in (("fork", .16), ("spoon", -.16))):
                raise RuntimeError("Nominal placement did not meet the target before injection; comparison stopped.")
            self.snapshot("before_disturbance.png")
            from embodichain.agents.agentchord.error_functions import misplaced_object
            self.injected = True  # One attempt only, including a native error.
            audit = _InjectionAudit(self.env)
            try:
                misplaced_object(audit.env, error_obj=OBJECT, error_pose=None, relative_error_xyz=SHIFT)
            except Exception as exc:
                self.emit("injection_error", error=f"{type(exc).__name__}: {exc}", **audit.details())
                raise
            after = {name: _pose_xyz(self.env, name) for name in ("plate", "fork", "spoon")}
            delta = [after[OBJECT][i]-before[OBJECT][i] for i in range(3)]
            details = dict(object=OBJECT, requested_xyz_m=SHIFT, measured_xyz_m=delta,
                before_objects=before, after_objects=after, native_settle_physics_steps=100, **audit.details(),
                setter_note="Submitted pose is an observed setter argument, not an instantaneous physical pose measurement.",
                camera_note="Native injection advances sim.update(100); these extra physics ticks are separate from env.step trace rows.")
            assessment = assess_injection({"edge": self.edge, "edge_step": self.edge_step, **details})
            self.emit("injection", **details, validation=assessment)
            self.snapshot("after_disturbance.png")
            if not assessment["valid"]:
                raise RuntimeError("Native injection did not meet its submitted-pose and post-physics displacement checks; see recovery_events.json.")
        if not self.enabled and self.edge == EDGE:
            from embodichain.agents.agentchord.monitor_functions import monitor_object_moved
            self.check(monitor_object_moved)

    def attach(self):
        from embodichain.agents.agentchord import agent_graph, graph_spec
        self.graph_module, self.spec_module = agent_graph, graph_spec
        self.original_compile = graph_spec.compile_agent_graph_from_file
        self.original_drive = agent_graph.drive
        original_compile, original_drive = self.original_compile, self.original_drive
        def compile_observed(*args, **kwargs):
            graph = original_compile(*args, **kwargs)
            graph.max_transitions = min(graph.max_transitions, 30)
            for edge in graph.edges.values():
                for field in ("left_arm_action", "right_arm_action"):
                    action = getattr(edge, field)
                    if action is None: continue
                    if getattr(action.func, "__name__", None) == "move_to_target_pose":
                        # graph JSON stays unchanged. Only normalize its matrix
                        # type before calling the unmodified native pose skill.
                        action = partial(action.func, **native_action_kwargs(self.env, {
                            "fn": "move_to_target_pose", "kwargs": action.keywords}))
                    def observed_action(*args, _edge=edge, _action=action, **kwargs):
                        self.begin(_edge)
                        return _action(*args, **kwargs)
                    setattr(edge, field, partial(observed_action))
                if edge.monitor_sequences:
                    sequences = []
                    for sequence in edge.monitor_sequences:
                        observed = []
                        for monitor in sequence:
                            def observed_monitor(_monitor=monitor):
                                return self.check(None, original=_monitor)
                            observed_monitor.__name__ = getattr(monitor.func, "__name__", "native_monitor")
                            observed.append(partial(observed_monitor))
                        sequences.append(observed)
                    edge.monitor_sequences = sequences
            return graph
        def drive_observed(*args, **kwargs):
            result = original_drive(*args, **kwargs)
            self.emit("graph_edge_end", monitor_index=result.get("monitor_index"),
                      monitor_name=result.get("monitor_name"), executed_steps=len(result.get("actions", [])))
            self.edge = None
            return result
        graph_spec.compile_agent_graph_from_file = compile_observed
        agent_graph.drive = drive_observed
        self.emit("observer_installed", recovery_enabled=self.enabled)
        return self

    def close(self):
        if self.original_compile is not None:
            self.spec_module.compile_agent_graph_from_file = self.original_compile
            self.graph_module.drive = self.original_drive
        self.write_json(self.run_dir / "recovery_events.json", {"enabled": self.enabled, "events": self.events})
        self.write_json(self.run_dir / "monitor_checks.json", self.checks)
